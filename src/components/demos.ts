export function fullPose(p: Pose, front?: boolean): FullPose {
  const off = (q: Pt): Pt => (front ? q : [q[0] - 4, q[1]])
  return { ...p, eL: p.eL ?? off(p.eR), hL: p.hL ?? off(p.hR), kL: p.kL ?? off(p.kR), fL: p.fL ?? off(p.fR) }
}
